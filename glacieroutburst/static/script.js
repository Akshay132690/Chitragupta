let areaChart = null;
document.getElementById("download-report").addEventListener("click", async () => {
    const lake = lakeSelector.value;
    const date = dateSelector.value;

    if (!lake || !date) {
        alert("Please select a lake and date first.");
        return;
    }

    // Fetch current analysis
    const res = await fetch(`/api/analyze?lake=${lake}&date=${date}`);
    const data = await res.json();

    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();

    let y = 20;

    // Title
    doc.setFontSize(18);
    doc.text("Glacier Lake Change Analysis Report", 105, y, { align: "center" });

    y += 12;
    doc.setLineWidth(0.5);
    doc.line(20, y, 190, y);

    y += 10;

    // Basic info
    doc.setFontSize(12);
    doc.text(`Lake Name: ${lake.toUpperCase()}`, 20, y); y += 8;
    doc.text(`Selected Date: ${date}`, 20, y); y += 8;
    doc.text(`Predicted Lake Area: ${data.lake_area_pixels} pixels`, 20, y); y += 8;
    doc.text(`Risk Level: ${data.risk_level}`, 20, y); y += 12;

    // Year-wise summary
    doc.setFontSize(14);
    doc.text("Year-wise Lake Area Change Summary", 20, y);
    y += 8;

    doc.setFontSize(11);

    // Build year-wise summary (same logic as cards)
    const resDates = await fetch(`/api/dates?lake=${lake}`);
    const dateData = await resDates.json();

    const yearMap = {};
    dateData.dates.forEach(d => {
        const year = d.substring(0, 4);
        yearMap[year] = d;
    });

    let prevArea = null;

    for (const year of Object.keys(yearMap).sort()) {
        const r = await fetch(`/api/analyze?lake=${lake}&date=${yearMap[year]}`);
        const d = await r.json();

        let line = `${year}: ${d.lake_area_pixels} px`;
        if (prevArea !== null) {
            const diff = d.lake_area_pixels - prevArea;
            line += diff >= 0 ? `  (+${diff})` : `  (${diff})`;
        }

        doc.text(line, 25, y);
        y += 7;
        prevArea = d.lake_area_pixels;

        if (y > 270) {
            doc.addPage();
            y = 20;
        }
    }

    // Footer
    y += 10;
    doc.setFontSize(10);
    doc.text("Generated by Glacier Lake Monitoring System", 105, y, { align: "center" });

    // Save PDF
    doc.save(`${lake}_${date}_Glacier_Report.pdf`);
});

