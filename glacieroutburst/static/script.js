async function loadLakes() {
    const res = await fetch("/api/lakes");
    const data = await res.json();

    lakeSelector.innerHTML = "";
    data.lakes.forEach(l => {
        const opt = document.createElement("option");
        opt.value = l.key;
        opt.textContent = l.name;
        lakeSelector.appendChild(opt);
    });

    loadDates();
}

// --------------------
// Load dates
// --------------------
async function loadDates() {
    const lake = lakeSelector.value;

    const res = await fetch(`/api/dates?lake=${lake}`);
    const data = await res.json();

    // Clear all date selectors
    dateSelector.innerHTML = "";
    compareDate1.innerHTML = "";
    compareDate2.innerHTML = "";

    data.dates.forEach(d => {
        const optMain = new Option(d, d);
        const opt1 = new Option(d, d);
        const opt2 = new Option(d, d);

        dateSelector.add(optMain);
        compareDate1.add(opt1);
        compareDate2.add(opt2);
    });

    // Auto-analyze first date
    if (data.dates.length > 0) {
        dateSelector.value = data.dates[0];
        analyze();
        setTimeout(() => renderYearWiseCards(lake, data.dates), 100);
        setTimeout(() => renderTimeline(lake, data.dates), 100);

    }
}

async function renderTimeline(lake, dates) {
    const svg = document.getElementById("timeline-chart");
    svg.innerHTML = "";

    // STEP 1: collect one value per year (last date of year)
    const yearEnd = {};

    for (const d of dates) {
        const year = d.substring(0, 4);
        yearEnd[year] = d; // last overwrite = end of year
    }

    const years = Object.keys(yearEnd).sort();
    if (years.length < 2) {
        console.warn("Not enough years for timeline");
        return;
    }

    // STEP 2: fetch areas ONLY for year-end dates
    const values = [];
    for (const y of years) {
        const res = await fetch(`/api/analyze?lake=${lake}&date=${yearEnd[y]}`);
        const data = await res.json();
        values.push(data.lake_area_pixels);
    }

    // STEP 3: normalize & draw
    const maxVal = Math.max(...values);
    const minVal = Math.min(...values);

    const W = 1000, H = 300, P = 80;

    const points = values.map((v, i) => {
        const x = P + (i / (values.length - 1)) * (W - 2 * P);
        const norm = (v - minVal) / (maxVal - minVal || 1);
        const y = H - P - norm * (H - 2 * P);
        return { x, y, year: years[i] };
    });

    // LINE
    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute(
        "d",
        points.map((p, i) => `${i === 0 ? "M" : "L"} ${p.x} ${p.y}`).join(" ")
    );
    path.setAttribute("stroke", "#00796b");
    path.setAttribute("stroke-width", "4");
    path.setAttribute("fill", "none");
    svg.appendChild(path);

    // POINTS + LABELS
    points.forEach(p => {
        const c = document.createElementNS("http://www.w3.org/2000/svg", "circle");
        c.setAttribute("cx", p.x);
        c.setAttribute("cy", p.y);
        c.setAttribute("r", 7);
        c.setAttribute("fill", "#00796b");
        svg.appendChild(c);

        const t = document.createElementNS("http://www.w3.org/2000/svg", "text");
        t.setAttribute("x", p.x);
        t.setAttribute("y", H - 20);
        t.setAttribute("text-anchor", "middle");
        t.setAttribute("font-size", "14");
        t.setAttribute("fill", "#333");
        t.textContent = p.year;
        svg.appendChild(t);
    });
}



// --------------------
// Analyze single date
// --------------------
async function analyze() {
    const lake = lakeSelector.value;
    const date = dateSelector.value;
    if (!lake || !date) return;

    const res = await fetch(`/api/analyze?lake=${lake}&date=${date}`);
    const data = await res.json();

    originalImg.src = data.original_image_url;
    predictedMaskImg.src = data.mask_image_url;

    lakeAreaSpan.textContent = data.lake_area_pixels;
    confidenceSpan.textContent = data.risk_level;

    updateRiskMeter(data.risk_level);
    updateAreaBar(data.lake_area_pixels);
}

// --------------------
// Risk meter
// --------------------
function updateRiskMeter(level) {
    let deg = -45;
    if (level === "Moderate") deg = 0;
    if (level === "High") deg = 45;
    riskNeedle.style.transform = `rotate(${deg}deg)`;
}

// --------------------
// Area bar
// --------------------
function updateAreaBar(area) {
    const fill = document.getElementById("area-fill");
    const max = 12000;
    const percent = Math.min((area / max) * 100, 100);
    fill.style.width = percent + "%";
}

async function renderYearWiseCards(lake, dates) {
    const container = document.getElementById("change-cards");
    container.innerHTML = "";

    // Group dates by year
    const yearMap = {};
    dates.forEach(d => {
        const year = d.substring(0, 4);
        if (!yearMap[year]) yearMap[year] = [];
        yearMap[year].push(d);
    });

    // Process each year
    for (const year of Object.keys(yearMap).sort()) {
        const yearDates = yearMap[year].sort();

        // First and last date of the year
        const startDate = yearDates[0];
        const endDate = yearDates[yearDates.length - 1];

        const startRes = await fetch(`/api/analyze?lake=${lake}&date=${startDate}`);
        const startData = await startRes.json();

        const endRes = await fetch(`/api/analyze?lake=${lake}&date=${endDate}`);
        const endData = await endRes.json();

        const startArea = startData.lake_area_pixels;
        const endArea = endData.lake_area_pixels;
        const diff = endArea - startArea;

        let deltaText = "—";
        let deltaClass = "same";

        if (diff > 0) {
            deltaText = `↑ +${diff} px`;
            deltaClass = "up";
        } else if (diff < 0) {
            deltaText = `↓ ${diff} px`;
            deltaClass = "down";
        }

        let riskClass = "risk-low";
        if (endData.risk_level === "Moderate") riskClass = "risk-moderate";
        if (endData.risk_level === "High") riskClass = "risk-high";

        const card = document.createElement("div");
        card.className = "change-card";

        card.innerHTML = `
            <div class="date">${year}</div>

            <div class="area">
                ${startArea} → ${endArea}
                <span>pixels</span>
            </div>

            <div class="change-meta">
                <div class="delta ${deltaClass}">${deltaText}</div>
                <div class="risk-tag ${riskClass}">${endData.risk_level}</div>
            </div>
        `;

        container.appendChild(card);
    }
}

// --------------------
// Chart (area over time)
// --------------------


async function drawChart(lake, dates) {
    const areas = [];

    for (const d of dates) {
        const res = await fetch(`/api/analyze?lake=${lake}&date=${d}`);
        const data = await res.json();
        areas.push(data.lake_area_pixels);
    }

    const ctx = document.getElementById("area-chart").getContext("2d");

    if (areaChart) areaChart.destroy();

    areaChart = new Chart(ctx, {
        type: "line",
        data: {
            labels: dates,
            datasets: [{
                label: "Lake Area Over Time (pixels)",
                data: areas,
                borderColor: "#00796b",
                backgroundColor: "rgba(0,121,107,0.2)",
                tension: 0.3,
                fill: true
            }]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false
        }
    });
}


